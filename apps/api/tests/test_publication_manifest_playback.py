"""Manifest selection uses the same playback resolver as public delivery.

Generated bytes test path/selection and hash metadata. They are not an MP4
codec, HTTP endpoint, database, or destination publication test.
"""
from __future__ import annotations

import hashlib
from types import SimpleNamespace
from uuid import uuid4

import pytest

from app.core.config import settings
from app.services import media_transcode, publication_manifest, publication_manifest_store


BODY = b"generated publication playback selection fixture"
SHA = hashlib.sha256(BODY).hexdigest()


def _setup(tmp_path, monkeypatch, kind="generation"):
    media = tmp_path / "media"
    media.mkdir()
    monkeypatch.setattr(settings, "media_root", str(media))
    monkeypatch.setattr(settings, "transcode_output_subdir", "transcoded")
    video = SimpleNamespace(
        id=uuid4(), stable_video_id="generated-public-video",
        publication_generation_id=None, playback_storage_key=None,
        playback_sha256_checksum=SHA, playback_file_size_bytes=len(BODY),
    )
    if kind == "generation":
        video.publication_generation_id = uuid4()
        path = media / ".loci-publication-generations" / str(video.publication_generation_id) / "files/video.mp4"
        video.source_path = str(path)
    elif kind == "validated":
        video.playback_storage_key = f"{video.id}.{SHA}.{'c' * 32}.mp4"
        path = media / "transcoded" / video.playback_storage_key
    else:
        path = media / "transcoded" / f"{video.id}.mp4"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(BODY)
    return media, video, path


def _selected_items(video):
    return publication_manifest_store._media_manifest_payload(
        object_row=SimpleNamespace(website_object_id="generated-public-object"),
        model=None, videos=[video], clips=[],
    )["items"]


def _assert_selected(media, video, path):
    assert media_transcode.video_playback_path(video) == path
    assert publication_manifest._video_stream_url(video) == f"/api/v1/public/videos/{video.id}/stream"
    items = _selected_items(video)
    assert len(items) == 1
    assert items[0]["kind"] == "video_stream"
    assert items[0]["relpath"] == path.relative_to(media).as_posix()
    assert items[0]["checksum"] == f"sha256:{SHA}"
    assert items[0]["sizeBytes"] == len(BODY)
    assert items[0]["owner"]["internalId"] == str(video.id)
    assert items[0]["owner"]["publicId"] == video.stable_video_id


def test_generation_file_is_selected_without_any_legacy_alias(tmp_path, monkeypatch):
    media, video, path = _setup(tmp_path, monkeypatch)
    assert not media_transcode.transcode_output_path(str(video.id)).exists()
    _assert_selected(media, video, path)


def test_ordinary_legacy_rendition_remains_selected(tmp_path, monkeypatch):
    media, video, path = _setup(tmp_path, monkeypatch, "legacy")
    _assert_selected(media, video, path)


def test_validated_versioned_rendition_is_selected_without_legacy_alias(tmp_path, monkeypatch):
    media, video, path = _setup(tmp_path, monkeypatch, "validated")
    assert not media_transcode.transcode_output_path(str(video.id)).exists()
    _assert_selected(media, video, path)


def test_missing_selected_generation_never_falls_back_to_a_stale_legacy_alias(tmp_path, monkeypatch):
    _media, video, path = _setup(tmp_path, monkeypatch)
    path.unlink()
    alias = media_transcode.transcode_output_path(str(video.id))
    alias.parent.mkdir(parents=True)
    alias.write_bytes(b"stale generated alias")
    assert publication_manifest._video_stream_url(video) is None
    assert _selected_items(video) == []


@pytest.mark.parametrize("invalid", ["generation", "other_video_key", "checksum", "token", "outside_generation"])
def test_invalid_selection_is_refused_even_when_a_legacy_alias_exists(tmp_path, monkeypatch, invalid):
    media, video, _path = _setup(tmp_path, monkeypatch, "validated" if invalid != "generation" else "generation")
    if invalid == "generation":
        video.publication_generation_id = "not-a-generation-uuid"
    elif invalid == "other_video_key":
        video.playback_storage_key = f"{uuid4()}.{SHA}.{'c' * 32}.mp4"
    elif invalid == "checksum":
        video.playback_sha256_checksum = "b" * 64
    elif invalid == "token":
        video.playback_storage_key = f"{video.id}.{SHA}.not-a-valid-token.mp4"
    else:
        video.publication_generation_id = uuid4()
        outside = media / "outside-generation.mp4"
        outside.write_bytes(BODY)
        video.source_path = str(outside)
    alias = media_transcode.transcode_output_path(str(video.id))
    alias.parent.mkdir(parents=True, exist_ok=True)
    alias.write_bytes(b"stale generated alias")
    assert media_transcode.video_playback_path(video) is None
    assert publication_manifest._video_stream_url(video) is None
    assert _selected_items(video) == []
