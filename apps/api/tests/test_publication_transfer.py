"""Exercise real bounded child pipes and generated open-file selection inputs.

These are local transport-boundary tests, not SSH or destination acceptance.
"""
import hashlib
import io
import os
from pathlib import Path
import sys
import tempfile
import unittest
from uuid import uuid4

from app.services.publication_selection_store import (
    SelectionError, opened_verified_bundle, seal_selection,
)
from app.services.publication_transfer import stream_command


class PublicationTransferTests(unittest.TestCase):
    def transfer(self, code, data=b"generated bytes", **changes):
        arguments = {"expected_bytes": len(data), "expected_sha256": hashlib.sha256(data).hexdigest(), "timeout": 5}
        arguments.update(changes)
        return stream_command([sys.executable, "-I", "-B", "-c", code], io.BytesIO(data), **arguments)

    def test_real_child_receives_exact_bytes_and_returns_digest(self):
        data = b"generated pipe content" * 65536
        output = self.transfer("import hashlib,sys; print(hashlib.sha256(sys.stdin.buffer.read()).hexdigest())", data)
        self.assertEqual(output.strip().decode(), hashlib.sha256(data).hexdigest())

    def test_duplex_reads_child_output_before_input_to_avoid_pipe_deadlock(self):
        output = self.transfer("import sys; sys.stdout.buffer.write(b'x'*65536); sys.stdout.flush(); sys.stdin.buffer.read()", b"y" * 262144)
        self.assertEqual(output, b"x" * 65536)

    def test_empty_content_can_be_transferred(self):
        self.assertEqual(self.transfer("import sys; assert sys.stdin.buffer.read()==b''", b""), b"")

    def test_oversize_child_output_is_rejected(self):
        with self.assertRaisesRegex(ValueError, "output exceeds"):
            self.transfer("import sys; sys.stdout.buffer.write(b'x'*65537); sys.stdout.flush(); sys.stdin.buffer.read()")

    def test_early_exit_and_nonzero_child_are_rejected(self):
        for code in ("raise SystemExit(7)", "import sys; sys.stdin.close(); raise SystemExit(3)"):
            with self.subTest(code=code), self.assertRaises((ValueError, BrokenPipeError)):
                self.transfer(code, b"x" * 262144)

    def test_timeout_reaps_only_the_owned_child(self):
        with self.assertRaises((TimeoutError, ValueError)):
            self.transfer("import time; time.sleep(30)", timeout=0.1)

    def test_wrong_length_and_digest_are_rejected(self):
        for changes in ({"expected_bytes": 2}, {"expected_bytes": 500}, {"expected_sha256": "0" * 64}):
            with self.subTest(changes=changes), self.assertRaises(ValueError):
                self.transfer("import sys; sys.stdin.buffer.read()", **changes)


class OpenSelectionDescriptorTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix="loci-generated-transfer-")
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name).resolve()
        (self.root / "generated.glb").write_bytes(b"generated media bytes")
        self.ident = str(uuid4())
        self.seal = seal_selection(self.root, self.ident, {"media_paths": ["generated.glb"]},
                                   ["generated.glb"], "a" * 64, max_bytes=4096)

    def opened(self):
        return opened_verified_bundle(self.root, self.ident, self.seal["selection_ref"],
                                      self.seal["selection_digest"], self.seal["metadata"])

    def test_open_descriptor_remains_sealed_when_live_authoring_file_changes(self):
        (self.root / "generated.glb").write_bytes(b"new authoring revision")
        with self.opened() as stream:
            self.assertEqual(hashlib.file_digest(stream, "sha256").hexdigest(), self.seal["metadata"]["bundle_sha256"])

    def test_bundle_replacement_cannot_change_bytes_on_open_descriptor(self):
        with self.assertRaises(SelectionError):
            with self.opened() as stream:
                original = stream.read()
                path = self.root / ".loci-publication-selections" / self.ident / "media.tar.gz"
                os.chmod(path.parent, 0o700)
                path.rename(path.with_name("retained-original.tar.gz"))
                path.write_bytes(b"replacement bytes")
                stream.seek(0)
                self.assertEqual(stream.read(), original)

    def test_selection_directory_replacement_is_rejected(self):
        with self.assertRaises(SelectionError):
            with self.opened() as stream:
                directory = self.root / ".loci-publication-selections" / self.ident
                directory.rename(directory.with_name("retained-old-selection"))
                directory.mkdir(mode=0o700)
                self.assertGreater(len(stream.read()), 0)


if __name__ == "__main__":
    unittest.main()
